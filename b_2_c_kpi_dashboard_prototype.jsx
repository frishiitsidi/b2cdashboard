  const isLocked = week.status === "locked";
  const attention = rows.filter(({ def, entry }) => ["yellow", "red"].includes(getStatus(def, entry)));

  const review = weeklyReviews[weekId] || {
    revenueTotal: "",
    leadsIn: "",
    followUpRate: "",
    conversionNotes: "",
    decisionsMade: "",
    prioritiesNextWeek: "",
  };

  const [saving, setSaving] = useState(false);
  const [success, setSuccess] = useState(false);
  const [errorMsg, setErrorMsg] = useState(null);

  const saveReview = async (shouldLock = false) => {
    if (isLocked) return;
    setSaving(true);
    setErrorMsg(null);
    try {
      const rawRev = review.revenueTotal ? String(review.revenueTotal).replace(/[^0-9]/g, "") : "";
      const revNum = rawRev ? Number(rawRev) : null;
      const leadsNum = review.leadsIn ? Number(review.leadsIn) : null;

      const dbPayload = {
        week_id: weekId,
        revenue_total: revNum,
        leads_in: leadsNum,
        follow_up_rate: review.followUpRate || "",
        conversion_notes: review.conversionNotes || "",
        decisions_made: review.decisionsMade || "",
        priorities_next_week: review.prioritiesNextWeek || "",
        updated_at: new Date().toISOString()
      };

      const { error } = await supabase
        .from("weekly_reviews")
        .upsert(dbPayload, { onConflict: "week_id" });

      if (error) throw error;

      if (shouldLock) {
        await setWeekStatus(weekId, "locked");
      }

      setSuccess(true);
      setTimeout(() => setSuccess(false), 3000);
    } catch (err) {
      console.error("Failed to save weekly review:", err);
      setErrorMsg(err.message || "Failed to save weekly review.");
    } finally {
      setSaving(false);
    }
  };

