export default function B2CKPIDashboardPrototype() {
  const [active, setActive] = useState("home");
  const [weekId, setWeekId] = useState("w3");
  const [roles, setRoles] = useState([]);
  const [entries, setEntries] = useState([]);
  const [selectedRole, setSelectedRole] = useState("all");
  const [weeks, setWeeks] = useState([]);
  const [kpis, setKpis] = useState([]);
  const [weeklyReviews, setWeeklyReviews] = useState({});
  const [monthlyReviews, setMonthlyReviews] = useState({
    whatWorked: "",
    whatDidntWork: "",
    prioritiesNextMonth: ""
  });
  
  const [loading, setLoading] = useState(true);
  const [dbError, setDbError] = useState(null);
  const [actionError, setActionError] = useState(null);

  const fetchData = async () => {
    setLoading(true);
    setDbError(null);
    try {
      if (!supabase) {
        throw new Error("Supabase client is not initialized. Please verify that VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY are correctly configured as environment variables in your Netlify settings, and then trigger a new deploy.");
      }
      const { data: dbRoles, error: rolesError } = await supabase.from("roles").select("*").order("name");
      if (rolesError) throw rolesError;
      
      const { data: dbWeeks, error: weeksError } = await supabase.from("weeks").select("*").order("created_at");
      if (weeksError) throw weeksError;
      
      const { data: dbKpis, error: kpisError } = await supabase.from("kpi_definitions").select("*");
      if (kpisError) throw kpisError;

      const { data: dbEntries, error: entriesError } = await supabase.from("kpi_entries").select("*");
      if (entriesError) throw entriesError;

      const { data: dbWeekly, error: weeklyError } = await supabase.from("weekly_reviews").select("*");
      if (weeklyError) throw weeklyError;

      const { data: dbMonthly, error: monthlyError } = await supabase.from("monthly_reviews").select("*").order("created_at", { ascending: false });
      if (monthlyError) throw monthlyError;

      setRoles(dbRoles);

      const mappedWeeks = dbWeeks.map(w => ({
        id: w.id,
        label: w.label,
        status: w.status,
        quarterWeek: w.quarter_week
      }));
      setWeeks(mappedWeeks);

      const mappedKpis = dbKpis.map(k => ({
        id: k.id,
        roleId: k.role_id,
        name: k.name,
        description: k.description,
        inputType: k.input_type,
        displayType: k.display_type,
        target: k.input_type === 'status' ? k.target_status : Number(k.target_value),
        unit: k.unit,
        numeratorLabel: k.numerator_label,
        denominatorLabel: k.denominator_label,
        checklistItems: k.checklist_items || []
      }));
      setKpis(mappedKpis);

      const mappedEntries = dbEntries.map(e => {
        const def = mappedKpis.find(k => k.id === e.kpi_id);
        return {
          id: e.id,
          weekId: e.week_id,
          kpiId: e.kpi_id,
          actual: def?.inputType === 'status' ? e.actual_status : (e.actual_value !== null ? Number(e.actual_value) : null),
          numerator: e.numerator_value !== null ? Number(e.numerator_value) : null,
          denominator: e.denominator_value !== null ? Number(e.denominator_value) : null,
          checklist: e.checklist_values || null,
          notes: e.notes,
          blocker: e.blocker,
          nextAction: e.next_action,
          updatedBy: e.updated_by,
          updatedAt: e.updated_at
        };
      });
      setEntries(mappedEntries);

      const mappedWeekly = {};
      dbWeekly.forEach(r => {
        mappedWeekly[r.week_id] = {
          revenueTotal: r.revenue_total !== null ? `Rp${Number(r.revenue_total).toLocaleString('id-ID')}` : "",
          leadsIn: r.leads_in !== null ? String(r.leads_in) : "",
          followUpRate: r.follow_up_rate || "",
          conversionNotes: r.conversion_notes || "",
          decisionsMade: r.decisions_made || "",
          prioritiesNextWeek: r.priorities_next_week || ""
        };
      });
      setWeeklyReviews(mappedWeekly);

      if (dbMonthly && dbMonthly.length > 0) {
        const m = dbMonthly[0];
        setMonthlyReviews({
          id: m.id,
          whatWorked: m.what_worked || "",
          whatDidntWork: m.what_needs_improvement || "",
          prioritiesNextMonth: m.focus_areas_next_month || ""
        });
      } else {
        setMonthlyReviews({
          whatWorked: "",
          whatDidntWork: "",
          prioritiesNextMonth: ""
        });
      }
      
      const currentWeek = mappedWeeks.find(w => w.status === 'current');
      if (currentWeek) {
        setWeekId(currentWeek.id);
      } else if (mappedWeeks.length > 0) {
        setWeekId(mappedWeeks[0].id);
      }
    } catch (err) {
      console.error("Error loading data from Supabase:", err);
      setDbError(err.message || "Failed to sync with database.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchData();
  }, []);

  async function setWeekStatus(id, status) {
    setActionError(null);
    try {
      const { error } = await supabase
        .from("weeks")
        .update({ status })
        .eq("id", id);
      
      if (error) throw error;
      
      setWeeks((prev) =>
        prev.map((w) => (w.id === id ? { ...w, status } : w))
      );
    } catch (err) {
      console.error("Failed to update week status in Supabase:", err);
      setActionError(`Failed to update week status: ${err.message}`);
    }
  }

  if (loading) {
    return (
      <div className="flex min-h-screen flex-col items-center justify-center bg-[#f5f5f7] font-sans text-[#1d1d1f]">
        <div className="relative flex flex-col items-center">
          <div className="h-10 w-10 animate-spin rounded-full border-2 border-black/5 border-t-black" />
          <div className="mt-5 text-sm font-medium tracking-tight text-[#1d1d1f]">Syncing with Supabase...</div>
          <div className="mt-1.5 text-xs text-[#86868b]">Securing live growth metrics</div>
        </div>
      </div>
    );
  }

  if (dbError) {
    return (
      <div className="flex min-h-screen flex-col items-center justify-center bg-[#f5f5f7] font-sans p-6 text-center">
        <div className="max-w-md rounded-[32px] bg-white p-8 shadow-sm ring-1 ring-black/5">
          <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-rose-50 text-rose-600">
            <CircleAlert size={24} />
          </div>
          <h2 className="mt-5 text-xl font-semibold tracking-tight text-[#1d1d1f]">Database Connection Failed</h2>
          <p className="mt-3 text-sm leading-6 text-[#6e6e73]">
            We encountered an error syncing with Supabase: <code className="block mt-2 rounded-xl bg-neutral-100 p-2.5 text-xs text-rose-600 font-mono break-all">{dbError}</code>
          </p>
          <button 
            onClick={fetchData} 
            className="mt-6 rounded-full bg-black text-white px-5 py-2.5 text-sm font-medium hover:bg-black/90 transition"
          >
            Retry Connection
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[#f5f5f7] font-sans text-[#1d1d1f]">
      <Header active={active} setActive={setActive} weekId={weekId} setWeekId={setWeekId} weeks={weeks} />
      {actionError && (
        <div className="mx-auto mt-4 max-w-7xl px-6">
          <div className="rounded-[20px] bg-rose-50 text-rose-800 p-4 text-sm leading-6 ring-1 ring-rose-200 flex items-center justify-between shadow-sm">
            <div className="flex items-center gap-3">
              <CircleAlert size={16} className="text-rose-600" />
              <span><strong>Action Failed:</strong> {actionError}</span>
            </div>
            <button onClick={() => setActionError(null)} className="text-rose-500 hover:text-rose-700 font-medium">Dismiss</button>
          </div>
        </div>
      )}
      {active === "home" && <Home setActive={setActive} />}
      {active === "dashboard" && <Dashboard roles={roles} entries={entries} weekId={weekId} setActive={setActive} setSelectedRole={setSelectedRole} weeks={weeks} kpis={kpis} />}
      {active === "tracking" && <KpiTracking roles={roles} entries={entries} setEntries={setEntries} weekId={weekId} selectedRole={selectedRole} setSelectedRole={setSelectedRole} weeks={weeks} kpis={kpis} />}
      {active === "history" && <KpiHistory roles={roles} entries={entries} selectedRole={selectedRole} setSelectedRole={setSelectedRole} weeks={weeks} kpis={kpis} />}
      {active === "weekly" && <WeeklyReview roles={roles} entries={entries} weekId={weekId} setWeekStatus={setWeekStatus} weeks={weeks} kpis={kpis} weeklyReviews={weeklyReviews} setWeeklyReviews={setWeeklyReviews} />}
      {active === "campaign" && <PlannedModulePage title="Campaign Library" subtitle="A future module for campaign archive, A/B testing history, creative learning, and post-campaign evaluation." features={["Campaign archive", "A/B test tracker", "Result and learning log"]} setActive={setActive} />}
      {active === "business" && <PlannedModulePage title="Business Performance History" subtitle="A future module for product revenue history, funnel trend, business performance recap, and quarterly growth view." features={["Revenue by product", "Funnel performance trend", "Quarterly business recap"]} setActive={setActive} />}
      {active === "learningJourney" && <PlannedModulePage title="Intern Learning Journey" subtitle="A future module for intern onboarding, learning milestones, assignment visibility, and readiness tracking." features={["Learning milestones", "Assignment progress", "Readiness evaluation"]} setActive={setActive} />}
      {active === "monthly" && <MonthlyReview roles={roles} entries={entries} weeks={weeks} kpis={kpis} monthlyReviews={monthlyReviews} setMonthlyReviews={setMonthlyReviews} />}
      {active === "setup" && <KpiSetup roles={roles} kpis={kpis} setKpis={setKpis} />}
      <div className="mx-auto max-w-7xl px-6 pb-10 text-center text-xs text-[#a1a1a6]">
        Prototype v3 · B2C Growth Operating System shell · KPI Tracker active MVP · Planned modules prepared
      </div>
    </div>
  );
}
